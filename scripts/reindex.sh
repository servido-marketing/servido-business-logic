#!/usr/bin/env bash
# Rebuild INDEX.md (human) and index.json (machine) from card frontmatter.
# Usage: scripts/reindex.sh
set -euo pipefail
cd "$(dirname "$0")/.."

field() { echo "$1" | awk -F': *' -v k="$2" '$0 ~ "^"k":"{sub("^"k": *","");print;exit}'; }

json='[' ; first=1
md="# Business Logic — Index\n\n"
md+="_Generated by scripts/reindex.sh. Do not edit by hand._\n\n"
md+="One row per rule card. Workers: \`git pull\`, grep this file for your task's domain/tags, then read the matched cards. Every \`active\` card is a binding constraint.\n\n"

declare -A by_domain
while IFS= read -r f; do
  fm=$(awk 'NR==1&&$0=="---"{f=1;next} f&&$0=="---"{exit} f{print}' "$f")
  id=$(field "$fm" id); domain=$(field "$fm" domain); title=$(field "$fm" title)
  status=$(field "$fm" status); applies=$(field "$fm" applies_to); tags=$(field "$fm" tags)
  rel="${f#./}"
  by_domain["$domain"]+="| \`$id\` | $title | $status | $applies | $tags | [card]($rel) |"$'\n'

  [ $first -eq 0 ] && json+=','
  first=0
  esc() { echo "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }
  json+=$(printf '{"id":"%s","domain":"%s","title":"%s","status":"%s","applies_to":%s,"tags":%s,"path":"%s"}' \
    "$(esc "$id")" "$(esc "$domain")" "$(esc "$title")" "$(esc "$status")" \
    "$(echo "$applies" | sed 's/\[/["/; s/\]/"]/; s/, */","/g')" \
    "$(echo "$tags"    | sed 's/\[/["/; s/\]/"]/; s/, */","/g')" \
    "$(esc "$rel")")
done < <(find domains -name '*.md' -type f | sort)
json+=']'

for dom in $(printf '%s\n' "${!by_domain[@]}" | sort); do
  md+="## $dom\n\n"
  md+="| id | title | status | applies_to | tags | card |\n"
  md+="|----|-------|--------|-----------|------|------|\n"
  md+="${by_domain[$dom]}\n"
done

printf '%b' "$md" > INDEX.md
echo "$json" | python3 -m json.tool > index.json 2>/dev/null || echo "$json" > index.json
echo "Reindexed: $(find domains -name '*.md' | wc -l | tr -d ' ') card(s) -> INDEX.md, index.json"
